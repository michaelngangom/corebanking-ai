package org.apache.fineract.command.sample.web;

import static org.springframework.http.HttpStatus.INTERNAL_SERVER_ERROR;

import java.util.Map;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ControllerAdvice;
import org.springframework.web.bind.annotation.ExceptionHandler;

@Slf4j
@ControllerAdvice
public class DummyExceptionHandler {

    @ExceptionHandler(Throwable.class)
    public ResponseEntity<Map<String, String>> handleRuntimeException(Throwable ex) {
        return ResponseEntity.status(INTERNAL_SERVER_ERROR).body(Map.of("error", ex.getMessage()));
    }
}
